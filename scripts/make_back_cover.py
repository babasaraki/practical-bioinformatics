#!/usr/bin/env python3
"""Typeset the back cover and the full paperback wrap at print resolution.

Palette and typeface are taken from the supplied front-cover artwork: the gold of its
diagonal band (sampled mean RGB 186,133,76), its light grey ground (230,231,233), its
near-black (27,27,27), and Helvetica Neue, the sans it sets the title in.

Geometry follows Amazon KDP's paperback specification. The spine is a function of the
page count - 0.002252 in per page for black ink on white paper - so the extent is a
command-line argument and the wrap must be rebuilt whenever it changes.

    python scripts/make_back_cover.py --pages 592 --photo images/author-photo.jpg

Writes dist/cover/back-cover-6x9.png (the back panel alone, for review) and
dist/cover/full-wrap-<N>pp.png (back + spine + front, with bleed, for upload).
"""
from __future__ import annotations

import argparse
import os
import textwrap

from PIL import Image, ImageDraw, ImageFont

DPI = 300
TRIM_W, TRIM_H = 6.0, 9.0
BLEED = 0.125
MARGIN = 0.5                      # safe margin inside the trim edge
PER_PAGE_IN = 0.002252            # KDP, black ink on white paper
BARCODE_W, BARCODE_H = 2.0, 1.2   # KDP overprints here; leave it white

GOLD = (186, 133, 76)
GREY = (230, 231, 233)
INK = (27, 27, 27)
WHITE = (255, 255, 255)

FONT = "/System/Library/Fonts/HelveticaNeue.ttc"


def px(inches: float) -> int:
    return round(inches * DPI)


def font(size_pt: float, bold: bool = False) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONT, round(size_pt * DPI / 72), index=1 if bold else 0)


def wrap(draw, text, fnt, width_px):
    """Greedy wrap on measured width rather than character count."""
    words, lines, cur = text.split(), [], ""
    for w in words:
        trial = f"{cur} {w}".strip()
        if draw.textlength(trial, font=fnt) <= width_px:
            cur = trial
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def draw_block(draw, text, fnt, x, y, width_px, leading, fill=INK):
    for line in wrap(draw, text, fnt, width_px):
        draw.text((x, y), line, font=fnt, fill=fill)
        y += leading
    return y


BLURB = [
    "This book teaches bioinformatics by doing it \u2014 making mistakes, and developing "
    "judgement about what the results mean.",
    "Every figure in these pages was generated by code printed in the book, running on "
    "data you download from public archives. Every command's output is shown as it was "
    "actually produced, including the places where a sensible default gives the wrong "
    "answer and you have to work out why. Nothing is illustrated with results that were "
    "never computed.",
    "It starts at the first command you type into a terminal and ends with a complete, "
    "reproducible analysis, written up to the standard a journal would expect.",
]

BULLETS = [
    "Work in Unix, Python and R, and judge which one a problem calls for",
    "Search GenBank, UniProt, Ensembl and ClinVar, and read what they return critically",
    "Align sequences, call variants, annotate a genome, and test it against a curated "
    "reference",
    "Measure a protein structure, and read an AlphaFold confidence score honestly",
    "Build networks, test enrichment, and spot a leaking machine-learning pipeline "
    "before it reaches a manuscript",
]

BIO = (
    "Umar Ahmad, PhD, is Senior Lecturer in the Department of Anatomy and the Human "
    "Genetics Informatics Unit at Sa'adu Zungur University, Bauchi, Nigeria, and Senior "
    "Technical Officer for Pathogen Genomics at the Africa Centres for Disease Control "
    "and Prevention, where he leads the AGARI genomic data platform and has contributed "
    "to continental and national genomic surveillance strategies. He works on cancer "
    "genomics, founded the genomics and bioinformatics company BioSeq, and has taught "
    "bioinformatics to researchers across Africa."
)

CREDENTIALS = ("16 chapters  \u00b7  137 exercises with worked solutions  \u00b7  "
               "49 computed figures  \u00b7  256-term glossary")


def place_photo(img, path, x, y, w, h, top_anchor=0.3):
    """Crop a photograph to fill the box exactly, without distorting it.

    The box is portrait 1.05 x 1.24 in; a headshot is usually narrower than that, so
    filling it means losing height rather than width. The surplus is taken mostly from
    the bottom - `top_anchor` is the fraction removed from the top - because a portrait
    wants a little headroom and cutting into the forehead looks like an accident.
    """
    photo = Image.open(path).convert("RGB")
    target = w / h
    pw, ph = photo.size
    if pw / ph > target:                      # too wide: crop width, centred
        new_w = round(ph * target)
        left = (pw - new_w) // 2
        photo = photo.crop((left, 0, left + new_w, ph))
    else:                                     # too tall: crop height
        new_h = round(pw / target)
        top = round((ph - new_h) * top_anchor)
        photo = photo.crop((0, top, pw, top + new_h))
    img.paste(photo.resize((w, h), Image.LANCZOS), (x, y))
    return photo.size


def back_panel(bleed: bool, photo: str | None = None) -> Image.Image:
    """The back cover. With bleed it is 6.125 x 9.25 in, for the wrap; without, 6 x 9.

    The page is laid out in one pass from the top, then the author block is placed in
    the space that remains above the reserved bottom strip. If the flowed copy would
    reach into that block the function raises rather than printing them on top of each
    other, which is what the first version of this script did.
    """
    b = BLEED if bleed else 0.0
    W, H = px(TRIM_W + b), px(TRIM_H + 2 * b)
    img = Image.new("RGB", (W, H), GREY)
    d = ImageDraw.Draw(img)

    left = px(b + MARGIN) if bleed else px(MARGIN)
    right = W - px(MARGIN)
    col = right - left
    y = px(b + MARGIN) if bleed else px(MARGIN)

    # Category line and the gold rule under it, echoing the band on the front.
    d.text((left, y), "B I O I N F O R M A T I C S   \u00b7   C O M P U T A T I O N A L   B I O L O G Y",
           font=font(8.5, bold=True), fill=GOLD)
    y += px(0.20)
    d.rectangle([left, y, right, y + px(0.03)], fill=GOLD)
    y += px(0.34)

    # Headline.
    y = draw_block(d, "Bioinformatics is learned the way laboratory work is learned: "
                      "by doing it.", font(17, bold=True), left, y, col, px(0.27))
    y += px(0.22)

    # Description.
    f_body = font(9.5)
    for para in BLURB:
        y = draw_block(d, para, f_body, left, y, col, px(0.168))
        y += px(0.11)

    y += px(0.06)
    d.text((left, y), "WHAT YOU WILL DO", font=font(8.5, bold=True), fill=GOLD)
    y += px(0.24)
    f_bul = font(9.5)
    for item in BULLETS:
        d.ellipse([left + px(0.02), y + px(0.050), left + px(0.065), y + px(0.095)], fill=GOLD)
        y = draw_block(d, item, f_bul, left + px(0.17), y, col - px(0.17), px(0.162))
        y += px(0.055)
    flowed_to = y

    # Reserved bottom strip: credentials rule, then the barcode box KDP overprints.
    strip_top = H - px((b + MARGIN) + BARCODE_H + 0.30)
    author_h = px(1.24)
    author_top = strip_top - author_h - px(0.12)
    if author_top < flowed_to:
        raise SystemExit(
            f"back cover copy overflows: text reaches {flowed_to / DPI:.2f} in but the "
            f"author block starts at {author_top / DPI:.2f} in. Shorten the copy or "
            f"reduce the body size."
        )

    # Author: photograph beside the 77-word biography.
    pw, ph = px(1.05), author_h
    if photo:
        place_photo(img, photo, left, author_top, pw, ph)
        # A hairline keyline in the cover's gold, so the portrait reads as placed
        # rather than dropped in. Drawn over the image, inside its edge.
        d.rectangle([left, author_top, left + pw - 1, author_top + ph - 1],
                    outline=GOLD, width=3)
    else:
        d.rectangle([left, author_top, left + pw, author_top + ph], outline=GOLD, width=4)
        for i, line in enumerate(["AUTHOR", "PHOTOGRAPH", "300 dpi", "1200 px min"]):
            d.text((left + px(0.10), author_top + px(0.40) + i * px(0.15)),
                   line, font=font(7.5), fill=GOLD)
    draw_block(d, BIO, font(8.5), left + px(1.22), author_top, col - px(1.22), px(0.148))

    # Credentials line above the reserved strip.
    d.rectangle([left, strip_top, right, strip_top + px(0.02)], fill=GOLD)
    d.text((left, strip_top + px(0.09)), CREDENTIALS, font=font(7.5, bold=True), fill=INK)

    # Barcode area: KDP overprints a 2.0 x 1.2 in box at bottom right. Keep it white.
    bx1 = right - px(BARCODE_W)
    by1 = H - px((b + MARGIN) + BARCODE_H)
    d.rectangle([bx1, by1, right, by1 + px(BARCODE_H)], fill=WHITE)
    d.text((bx1 + px(0.12), by1 + px(0.50)), "ISBN barcode", font=font(8), fill=(150, 150, 150))
    d.text((bx1 + px(0.12), by1 + px(0.66)), "printed here", font=font(8), fill=(150, 150, 150))

    # Imprint and ISBN, left of the barcode.
    d.text((left, by1 + px(0.26)), "[ IMPRINT ]", font=font(9.5, bold=True), fill=INK)
    d.text((left, by1 + px(0.48)), "ISBN 978-X-XXXXX-XXX-X", font=font(8), fill=INK)
    d.text((left, by1 + px(0.66)), "github.com/babasaraki/practical-bioinformatics",
           font=font(8), fill=GOLD)
    return img


def spine(pages: int) -> Image.Image:
    """Title, author and imprint, set along a spine of the computed width."""
    w_in = pages * PER_PAGE_IN
    img = Image.new("RGB", (px(w_in), px(TRIM_H + 2 * BLEED)), INK)
    H = img.height
    # Compose horizontally, then rotate: text along the spine reads top-to-bottom.
    strip = Image.new("RGB", (H, px(w_in)), INK)
    d = ImageDraw.Draw(strip)
    f_t, f_a = font(13, bold=True), font(10)
    title = "Practical Approach to Learning Bioinformatics"
    d.text((px(0.9), (px(w_in) - f_t.size) / 2 - px(0.06)), title, font=f_t, fill=WHITE)
    author = "UMAR AHMAD"
    d.text((H - px(0.9) - d.textlength(author, font=f_a),
            (px(w_in) - f_a.size) / 2 - px(0.02)), author, font=f_a, fill=GOLD)
    return strip.rotate(-90, expand=True)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pages", type=int, required=True, help="extent of the printed book")
    ap.add_argument("--front", default="images/cover.jpg")
    ap.add_argument("--photo", default=None,
                    help="author photograph; omit to leave the marked placeholder")
    ap.add_argument("--outdir", default="dist/cover")
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)

    back_panel(bleed=False, photo=a.photo).save(f"{a.outdir}/back-cover-6x9.png")

    sp = spine(a.pages)
    bk = back_panel(bleed=True, photo=a.photo)
    H = px(TRIM_H + 2 * BLEED)
    front_w = px(TRIM_W + BLEED)
    wrap_img = Image.new("RGB", (bk.width + sp.width + front_w, H), GREY)
    wrap_img.paste(bk, (0, 0))
    wrap_img.paste(sp, (bk.width, 0))

    # The front panel must bleed off three edges. The supplied artwork is 1:1.312
    # against the 1:1.51 of the bleed panel, so filling it would crop the title and the
    # author's name off the sides. It is fitted to the panel width and centred on the
    # artwork's own grey instead, and the panel is marked in the companion notes as
    # needing the high-resolution original before this goes to print.
    fr = Image.open(a.front).convert("RGB")
    scale = front_w / fr.width
    fr = fr.resize((front_w, round(fr.height * scale)), Image.LANCZOS)
    wrap_img.paste(fr, (bk.width + sp.width, (H - fr.height) // 2))

    out = f"{a.outdir}/full-wrap-{a.pages}pp.png"
    wrap_img.save(out)
    print(f"spine {a.pages * PER_PAGE_IN:.3f} in ({a.pages * PER_PAGE_IN * 25.4:.1f} mm)")
    print(f"{out}  {wrap_img.width} x {wrap_img.height} px "
          f"({wrap_img.width / DPI:.3f} x {wrap_img.height / DPI:.3f} in at {DPI} dpi)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
